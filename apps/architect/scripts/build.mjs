import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { build, loadEnv } from 'vite';

import { bundleLegacyApp } from '../../../scripts/buildtime/bundle-legacy-app.mjs';
import {
  legacyApp,
  loadLegacyAppV8,
} from '../../../scripts/buildtime/legacy-app.ts';

const appRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const legacyArchitect = legacyApp('architect');

// Decided first, so a release build that must bundle Architect 8 and cannot
// fails before Vite spends minutes building. Read from the environment Vite
// gives vite.config.ts, which makes the same decision for the define.
let legacyArchitectV8;
try {
  legacyArchitectV8 = loadLegacyAppV8(
    legacyArchitect,
    appRoot,
    loadEnv('production', appRoot, ''),
  );
} catch (error) {
  console.error(
    `Architect 8 bundling: ${error instanceof Error ? error.message : String(error)}`,
  );
  process.exit(1);
}

await build({ root: appRoot });
// After Vite, whose service worker has been generated by now, so Architect 8
// never enters this app's precache; before the assertion, which checks it.
await bundleLegacyApp({
  app: legacyArchitect,
  appRoot,
  dist: join(appRoot, 'dist'),
  pin: legacyArchitectV8.pin,
});
// The assertion reads the completed dist output, so load it only after Vite.
await import('./assert-pwa-build.mjs');
