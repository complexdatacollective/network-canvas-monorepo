export type LanguageChoice = {
  locale: LocaleTag;
  /** The language's name in the display language. */
  name: string;
  /** The language's name for itself. */
  autonym: string;
  direction: 'ltr' | 'rtl';
};

export const describeLanguage = (
  locale: LocaleTag,
  displayLocale: string,
): LanguageChoice => {
  const own = getLocaleMetadata(locale);
  return {
    locale: own.locale,
    name: getLocaleMetadata(locale, displayLocale).label,
    autonym: own.label,
    direction: own.direction,
  };
};

const choicesByDisplayLocale = new Map<string, readonly LanguageChoice[]>();

/** Every offered language, sorted by its name in the display language. */
export const getLanguageChoices = (
  displayLocale: string,
): readonly LanguageChoice[] => {
  const cached = choicesByDisplayLocale.get(displayLocale);
  if (cached) return cached;
  const collator = new Intl.Collator(displayLocale);
  const choices = LANGUAGE_TAGS.map((locale) =>
    describeLanguage(locale, displayLocale),
  ).toSorted((a, b) => collator.compare(a.name, b.name));
  choicesByDisplayLocale.set(displayLocale, choices);
  return choices;
};

/** The offered language that best fits `preferred` (Architect's own language). */
export const matchLanguageChoice = (preferred: string): LocaleTag =>
  selectProtocolLocale([preferred], {
    defaultLocale: 'en',
    locales: LANGUAGE_TAGS,
  });
