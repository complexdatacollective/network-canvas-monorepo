import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';

import { parse } from 'postcss';

const require = createRequire(import.meta.url);

// The canonical @font-face rules: the same files the apps and the shared
// header load, so the forum cannot drift onto a different cut of the fonts.
const FONT_SOURCES = [
  '@codaco/tailwind-config/fonts/nunito.css',
  '@codaco/tailwind-config/fonts/inclusive-sans.css',
  '@codaco/tailwind-config/fonts/readex-pro.css',
];

const FONTSOURCE_URL =
  /url\('(@fontsource-variable\/[^/]+)\/files\/([^']+\.woff2)'\)/;

export type ThemeFont = {
  /** The theme asset name, which Discourse exposes to SCSS as `$<asset>`. */
  asset: string;
  /** Where the font sits in the theme. */
  path: string;
  /** The woff2 file on disk. */
  source: string;
};

/**
 * Every face of the shared fonts, as theme assets, and the `@font-face`
 * rules that load them (`scss/fonts.scss`). Discourse serves a theme asset
 * from its own upload store, and the rule reaches it through the asset's SCSS
 * variable.
 */
export function themeFonts() {
  const fonts: ThemeFont[] = [];
  const faces: string[] = [];

  for (const sourceCss of FONT_SOURCES) {
    const cssPath = require.resolve(sourceCss);
    // The font packages are dependencies of tailwind-config, so resolve their
    // files from there.
    const requireFromCss = createRequire(cssPath);
    parse(readFileSync(cssPath, 'utf8')).walkAtRules('font-face', (face) => {
      face.walkDecls('src', (declaration) => {
        const match = FONTSOURCE_URL.exec(declaration.value);
        if (!match?.[1] || !match[2]) {
          throw new Error(
            `Unexpected @font-face src in ${sourceCss}: ${declaration.value}`,
          );
        }
        const [, fontPackage, file] = match;
        const asset = `nc-font-${file.replace(/\.woff2$/, '')}`;
        fonts.push({
          asset,
          path: `assets/fonts/${file}`,
          source: requireFromCss.resolve(`${fontPackage}/files/${file}`),
        });
        declaration.value = declaration.value.replace(
          FONTSOURCE_URL,
          `url($${asset})`,
        );
      });
      faces.push(face.toString());
    });
  }

  const scss = [
    '// Generated by scripts/build.ts from @codaco/tailwind-config. Do not edit.',
    ...faces,
    '',
  ].join('\n\n');

  return { fonts, scss };
}
