import { buildScopes, type Scope } from '@codaco/tailwind-config/theme-colors';

/**
 * Every custom property the default Network Canvas theme declares, renamed
 * from `--x` to `--nc-x` so it cannot collide with Discourse's own
 * `--primary`, `--secondary` and `--success`.
 *
 * Each value is the token's CSS with its `var()`s already substituted, so a
 * token stands alone and the browser still evaluates the `oklch()` and
 * `color-mix()` itself (keeping wide-gamut colour on displays that have it).
 * Tailwind's `--color-*` aliases are left out: the theme reads the tokens they
 * alias directly.
 */
function tokenDeclarations(scope: Scope) {
  return scope
    .propertyNames()
    .filter((name) => !name.startsWith('--color-'))
    .toSorted()
    .map((name) => {
      const value = scope.computed(name);
      if (value === undefined) {
        throw new Error(`${name} has no value in scope ${scope.name}`);
      }
      return `  --nc-${name.slice(2)}: ${value.replace(/\s+/g, ' ')};`;
    });
}

const indent = (lines: string[]) => lines.map((line) => `  ${line}`);

/**
 * `common/color_definitions.scss`. Discourse compiles this file once per
 * colour palette into the stylesheet that palette switches in, so the light
 * tokens apply under a light palette and the dark tokens under a dark one,
 * following the visitor's colour-mode choice with no selector of our own.
 */
export function colorDefinitionsScss() {
  const scopes = buildScopes();
  return [
    '// Generated by scripts/build.ts from @codaco/tailwind-config. Do not edit.',
    ':root {',
    '  @if is-dark-color-scheme() {',
    ...indent(tokenDeclarations(scopes['default-dark'])),
    '  } @else {',
    ...indent(tokenDeclarations(scopes['default-light'])),
    '  }',
    '}',
    '',
  ].join('\n');
}
