import { elevationShadow } from '@codaco/tailwind-config/elevation';
import { type Scope } from '@codaco/tailwind-config/theme-colors';
import { typeScale } from '@codaco/tailwind-config/type-scale';

import { forumScopes } from './scopes.ts';

/**
 * Every custom property the default Network Canvas theme declares, renamed
 * from `--x` to `--nc-x` so it cannot collide with Discourse's own
 * `--primary`, `--secondary` and `--success`.
 *
 * Each value is the token's CSS with its `var()`s already substituted, so a
 * token stands alone and the browser still evaluates the `oklch()` and
 * `color-mix()` itself (keeping wide-gamut colour on displays that have it).
 * Tailwind's `--color-*` aliases are left out: the theme reads the tokens they
 * alias directly.
 */
function tokenDeclarations(scope: Scope) {
  return scope
    .propertyNames()
    .filter((name) => !name.startsWith('--color-'))
    .toSorted()
    .map((name) => {
      const value = scope.computed(name);
      if (value === undefined) {
        throw new Error(`${name} has no value in scope ${scope.name}`);
      }
      return `  --nc-${name.slice(2)}: ${value.replace(/\s+/g, ' ')};`;
    });
}

/**
 * The shared `elevation-*` shadows as `--nc-elevation-*`, the values the
 * Tailwind utilities apply. Nothing in the forum publishes a background for
 * them to tint from, so they are the same in both colour modes, as they are
 * in the shared header.
 */
function elevationDeclarations() {
  return (['low', 'medium', 'high'] as const).map(
    (elevation) =>
      `  --nc-elevation-${elevation}: ${elevationShadow(elevation)};`,
  );
}

/**
 * The shared type scale as `--nc-text-<step>`, each with the
 * `--line-height` and `--letter-spacing` its `text-*` utility applies. The
 * sizes read the theme's root size as `--nc-theme-root-size`, declared with
 * the other tokens; nothing declares `--nc-theme-vw`, so the fluid middle
 * terms use the viewport, as they do outside the interview.
 */
function typeDeclarations() {
  return typeScale().flatMap(
    ({ name, fontSize, lineHeight, letterSpacing }) => [
      `  --nc-text-${name}: ${fontSize.replaceAll('var(--', 'var(--nc-')};`,
      `  --nc-text-${name}--line-height: ${lineHeight};`,
      `  --nc-text-${name}--letter-spacing: ${letterSpacing};`,
    ],
  );
}

/**
 * The forum's own values that differ between the colour modes and are not
 * colours: how strongly the home page's background glows (layout.scss). The
 * same tint shows far more against the dark page, so there it is a little
 * under half as strong.
 */
function forumDeclarations(mode: 'light' | 'dark') {
  return [`  --nc-glow-strength: ${mode === 'dark' ? 0.45 : 1};`];
}

const indent = (lines: string[]) => lines.map((line) => `  ${line}`);

/**
 * `common/color_definitions.scss`. Discourse compiles this file once per
 * colour palette into the stylesheet that palette switches in, so the light
 * tokens apply under a light palette and the dark tokens under a dark one,
 * following the visitor's colour-mode choice with no selector of our own.
 */
export function colorDefinitionsScss() {
  const scopes = forumScopes();
  return [
    '// Generated by scripts/build.ts from @codaco/tailwind-config. Do not edit.',
    ':root {',
    '  @if is-dark-color-scheme() {',
    ...indent(tokenDeclarations(scopes.dark)),
    ...indent(elevationDeclarations()),
    ...indent(typeDeclarations()),
    ...indent(forumDeclarations('dark')),
    '  } @else {',
    ...indent(tokenDeclarations(scopes.light)),
    ...indent(elevationDeclarations()),
    ...indent(typeDeclarations()),
    ...indent(forumDeclarations('light')),
    '  }',
    '}',
    '',
  ].join('\n');
}
