import { describe, expect, it } from 'vitest';

import {
  BIOLOGICAL_SEX_OPTIONS,
  GAMETE_ROLE_OPTIONS,
  RELATIONSHIP_TYPE_OPTIONS,
} from '@codaco/shared-consts';

import { migrateProtocol } from '../../migration/migrate-protocol.ts';
import validateProtocol from '../../validation/validate-protocol.ts';
import { repairConfigurationConflicts } from '../repairConfigurationConflicts.ts';

type Stage = Record<string, unknown>;

const familyPedigree = (overrides: Stage = {}): Stage => ({
  id: 'fp1',
  label: 'Family Pedigree',
  type: 'FamilyPedigree',
  nodeConfig: {
    type: 'family_member',
    nodeLabelVariable: 'fmName',
    egoVariable: 'isEgo',
    relationshipVariable: 'relationshipToEgo',
    biologicalSexVariable: 'biologicalSex',
  },
  edgeConfig: {
    type: 'family_edge',
    relationshipTypeVariable: 'relationshipType',
    isActiveVariable: 'isActive',
    isGestationalCarrierVariable: 'isGestationalCarrier',
    gameteRoleVariable: 'gameteRole',
  },
  censusPrompt: 'Build your family',
  framing: { mode: 'fixed', value: 'gamete' },
  boundaries: {
    requireGrandparents: 'off',
    requireChildrenContributors: 'off',
  },
  ...overrides,
});

const narrativePedigree = (diseases: Stage[]): Stage => ({
  id: 'np1',
  label: 'Narrative Pedigree',
  type: 'NarrativePedigree',
  sourceStageId: 'fp1',
  diseases,
});

const disease = (
  id: string,
  label: string,
  variable: string,
  color = 'node-color-seq-1',
): Stage => ({
  id,
  label,
  color,
  variable,
  inheritancePattern: 'autosomalDominant',
});

const protocolWith = (stages: Stage[]) => ({
  name: 'Pedigree protocol',
  schemaVersion: 8 as const,
  codebook: {
    node: {
      family_member: {
        name: 'Family member',
        color: 'node-color-seq-1',
        shape: { default: 'circle' as const },
        variables: {
          fmName: { name: 'fm_name', type: 'text', component: 'Text' },
          isEgo: { name: 'is_ego', type: 'boolean' },
          relationshipToEgo: { name: 'fm_relationship_to_ego', type: 'text' },
          biologicalSex: {
            name: 'biologicalSex',
            type: 'categorical',
            options: BIOLOGICAL_SEX_OPTIONS,
          },
          hasConditionX: { name: 'hasConditionX', type: 'boolean' },
          hadTesting: { name: 'hadTesting', type: 'boolean' },
          hasAsthma: { name: 'hasAsthma', type: 'boolean' },
          fmLayout: { name: 'fmLayout', type: 'layout' },
          age: { name: 'age', type: 'number', component: 'Number' },
        },
      },
    },
    edge: {
      family_edge: {
        name: 'Family edge',
        color: 'edge-color-seq-1',
        variables: {
          relationshipType: {
            name: 'relationshipType',
            type: 'categorical',
            options: RELATIONSHIP_TYPE_OPTIONS,
          },
          isActive: { name: 'isActive', type: 'boolean' },
          isGestationalCarrier: {
            name: 'isGestationalCarrier',
            type: 'boolean',
          },
          gameteRole: {
            name: 'gameteRole',
            type: 'categorical',
            options: GAMETE_ROLE_OPTIONS,
          },
        },
      },
    },
  },
  stages,
});

/** Every repair this module offers must yield a protocol that opens. */
const expectRepairsToValidate = async (protocol: unknown) => {
  const result = repairConfigurationConflicts(protocol);
  expect(result.problems.length).toBeGreaterThan(0);
  expect(result.repairable).toBe(true);
  const validation = await validateProtocol(
    result.protocol as Parameters<typeof validateProtocol>[0],
  );
  expect(validation.success ? null : validation.error.message).toBeNull();
  return result;
};

describe('repairConfigurationConflicts', () => {
  it('returns a clean protocol unchanged, by reference', () => {
    const protocol = protocolWith([
      familyPedigree({
        nominationPrompts: [
          { id: 'np', text: 'Who has this?', variable: 'hasConditionX' },
        ],
      }),
      narrativePedigree([disease('d1', 'Condition X', 'hasConditionX')]),
    ]);
    const result = repairConfigurationConflicts(protocol);
    expect(result.problems).toEqual([]);
    expect(result.repairable).toBe(true);
    expect(result.protocol).toBe(protocol);
  });

  it('offers to wrap the two undefined colors generated by the old pedigree picker', async () => {
    const protocol = protocolWith([
      familyPedigree(),
      narrativePedigree([
        disease('d1', 'Condition X', 'hasConditionX', 'node-color-seq-9'),
        disease('d2', 'Testing', 'hadTesting', 'node-color-seq-10'),
      ]),
    ]);

    const result = await expectRepairsToValidate(protocol);
    expect(result.problems).toEqual([
      {
        problem:
          'The disease "Condition X" uses "node-color-seq-9", which has no defined node palette color.',
        repair:
          'Its color will wrap to the defined palette reference "node-color-seq-1".',
      },
      {
        problem:
          'The disease "Testing" uses "node-color-seq-10", which has no defined node palette color.',
        repair:
          'Its color will wrap to the defined palette reference "node-color-seq-2".',
      },
    ]);
    const repairedStage = (result.protocol as { stages: Stage[] }).stages[1];
    expect(repairedStage?.diseases).toEqual([
      disease('d1', 'Condition X', 'hasConditionX', 'node-color-seq-1'),
      disease('d2', 'Testing', 'hadTesting', 'node-color-seq-2'),
    ]);
    expect(
      ((protocol.stages[1] as Stage).diseases as Stage[]).map(
        ({ color }) => color,
      ),
    ).toEqual(['node-color-seq-9', 'node-color-seq-10']);
  });

  it('normalizes old picker colors before migrateProtocol pre-validates v8', () => {
    const migrated = migrateProtocol(
      protocolWith([
        familyPedigree(),
        narrativePedigree([
          disease('d1', 'Condition X', 'hasConditionX', 'node-color-seq-9'),
          disease('d2', 'Testing', 'hadTesting', 'node-color-seq-10'),
        ]),
      ]),
    );

    const migratedStage = migrated.stages[1];
    expect(migratedStage?.type).toBe('NarrativePedigree');
    if (migratedStage?.type !== 'NarrativePedigree') return;
    expect(migratedStage.diseases.map(({ color }) => color)).toEqual([
      'node-color-seq-1',
      'node-color-seq-2',
    ]);
  });

  it.each(['#ff0000', 'custom-color', 'node-color-seq-11'])(
    'does not normalize unsupported protocol color %s',
    (color) => {
      const protocol = protocolWith([
        familyPedigree(),
        narrativePedigree([
          disease('d1', 'Condition X', 'hasConditionX', color),
        ]),
      ]);

      expect(repairConfigurationConflicts(protocol)).toEqual({
        protocol,
        problems: [],
        repairable: true,
      });
      expect(() => migrateProtocol(protocol)).toThrow(
        'Invalid protocol document for version 8',
      );
    },
  );

  it('drops a nomination prompt bound to the ego variable', async () => {
    const result = await expectRepairsToValidate(
      protocolWith([
        familyPedigree({
          nominationPrompts: [
            { id: 'np1', text: 'Who has this?', variable: 'hasConditionX' },
            { id: 'np2', text: 'Who is you?', variable: 'isEgo' },
          ],
        }),
      ]),
    );
    const stage = (result.protocol as { stages: Stage[] }).stages[0];
    expect(stage?.nominationPrompts).toEqual([
      { id: 'np1', text: 'Who has this?', variable: 'hasConditionX' },
    ]);
  });

  it('removes the whole nomination-prompt list when its only prompt conflicts', async () => {
    const result = await expectRepairsToValidate(
      protocolWith([
        familyPedigree({
          nominationPrompts: [
            { id: 'np1', text: 'Who is you?', variable: 'isEgo' },
          ],
        }),
      ]),
    );
    const stage = (result.protocol as { stages: Stage[] }).stages[0];
    expect(stage).not.toHaveProperty('nominationPrompts');
  });

  it('drops a repeated form field', async () => {
    const result = await expectRepairsToValidate(
      protocolWith([
        familyPedigree({
          nodeConfig: {
            type: 'family_member',
            nodeLabelVariable: 'fmName',
            egoVariable: 'isEgo',
            relationshipVariable: 'relationshipToEgo',
            biologicalSexVariable: 'biologicalSex',
            form: [
              { variable: 'age', prompt: 'How old?' },
              { variable: 'age', prompt: 'How old again?' },
            ],
          },
        }),
      ]),
    );
    const stage = (result.protocol as { stages: Stage[] }).stages[0] as {
      nodeConfig: { form: unknown[] };
    };
    expect(stage.nodeConfig.form).toEqual([
      { variable: 'age', prompt: 'How old?' },
    ]);
  });

  it('drops a repeated disease mapping and keeps the first', async () => {
    const result = await expectRepairsToValidate(
      protocolWith([
        familyPedigree(),
        narrativePedigree([
          disease('d1', 'Condition X', 'hasConditionX'),
          disease('d2', 'Condition Y', 'hasConditionX', 'node-color-seq-2'),
        ]),
      ]),
    );
    const stage = (result.protocol as { stages: Stage[] }).stages[1] as {
      diseases: { id: string }[];
    };
    expect(stage.diseases.map((row) => row.id)).toEqual(['d1']);
  });

  it('renames rather than removes a duplicate disease label', async () => {
    const result = await expectRepairsToValidate(
      protocolWith([
        familyPedigree(),
        narrativePedigree([
          disease('d1', 'Condition X', 'hasConditionX'),
          disease('d2', 'Condition X', 'hadTesting', 'node-color-seq-2'),
        ]),
      ]),
    );
    const stage = (result.protocol as { stages: Stage[] }).stages[1] as {
      diseases: { label: string }[];
    };
    expect(stage.diseases.map((row) => row.label)).toEqual([
      'Condition X',
      'Condition X (2)',
    ]);
    expect(result.problems[0]?.repair).toContain('Condition X (2)');
  });

  it('treats a whitespace/case-only difference as a duplicate label', async () => {
    const result = await expectRepairsToValidate(
      protocolWith([
        familyPedigree(),
        narrativePedigree([
          disease('d1', 'Condition X', 'hasConditionX'),
          disease('d2', '  condition x ', 'hadTesting', 'node-color-seq-2'),
        ]),
      ]),
    );
    const stage = (result.protocol as { stages: Stage[] }).stages[1] as {
      diseases: { label: string }[];
    };
    expect(stage.diseases[1]?.label).toBe('condition x (2)');
  });

  it('refuses when repairing would empty a required list', () => {
    // The bin's only prompt writes the pedigree's own ego marker: removing it
    // would leave `prompts: []`, which the schema rejects. Reporting the
    // problem as unrepairable is the whole point — a fix that produced a
    // second dead end would be worse than none.
    const result = repairConfigurationConflicts(
      protocolWith([
        familyPedigree(),
        {
          id: 'cb1',
          label: 'Sort your family',
          type: 'CategoricalBin',
          subject: { entity: 'node', type: 'family_member' },
          prompts: [{ id: 'p1', text: 'Sort', variable: 'isEgo' }],
        },
      ]),
    );
    expect(result.repairable).toBe(false);
    expect(result.problems).toHaveLength(1);
    expect(result.problems[0]?.repair).toBeUndefined();
    expect(result.problems[0]?.problem).toContain('is_ego');
  });

  // Rename paths carry the index a row had BEFORE anything was removed.
  // Applying them after a removal rewrote a DIFFERENT disease's
  // participant-facing name and left the real duplicate in place.
  it('renames the right row when another row is removed from the same list', async () => {
    const result = await expectRepairsToValidate(
      protocolWith([
        familyPedigree({
          nominationPrompts: [
            { id: 'np1', text: 'Who has this?', variable: 'hasConditionX' },
            { id: 'np2', text: 'Who is you?', variable: 'isEgo' },
          ],
        }),
        narrativePedigree([
          disease('d1', 'Cancer', 'hasConditionX'),
          disease('d2', 'cancer ', 'hadTesting', 'node-color-seq-2'),
          disease('d3', 'Asthma', 'hasAsthma', 'node-color-seq-3'),
        ]),
      ]),
    );
    const stage = (result.protocol as { stages: Stage[] }).stages[1] as {
      diseases: { id: string; label: string }[];
    };
    expect(stage.diseases.map((row) => [row.id, row.label])).toEqual([
      ['d1', 'Cancer'],
      ['d2', 'cancer (2)'],
      ['d3', 'Asthma'],
    ]);
  });

  // The generated name has to dodge EVERY surviving row, not only the ones
  // already walked past. Seeding the taken set as the walk went renamed this
  // row onto row 3's existing label, so the repaired protocol still failed the
  // duplicate-label rule and Architect looped the researcher back to the same
  // offer.
  it('does not rename a disease onto a label a later row already holds', async () => {
    const result = await expectRepairsToValidate(
      protocolWith([
        familyPedigree(),
        narrativePedigree([
          disease('d1', 'Asthma', 'hasConditionX'),
          disease('d2', 'Asthma', 'hadTesting', 'node-color-seq-2'),
          disease('d3', 'Asthma (2)', 'hasAsthma', 'node-color-seq-3'),
        ]),
      ]),
    );
    const stage = (result.protocol as { stages: Stage[] }).stages[1] as {
      diseases: { id: string; label: string }[];
    };
    expect(stage.diseases.map((row) => [row.id, row.label])).toEqual([
      ['d1', 'Asthma'],
      ['d2', 'Asthma (3)'],
      ['d3', 'Asthma (2)'],
    ]);
    expect(result.problems[0]?.repair).toContain('Asthma (3)');
  });

  // A row leaving the list cannot make the row that stays a duplicate of
  // anything. Renaming it produced a legend reading "Cancer (2)" with no
  // "Cancer" anywhere, and a repair sentence describing a rename nothing
  // required.
  it('leaves a disease alone when the row it duplicated is being removed', async () => {
    const result = await expectRepairsToValidate(
      protocolWith([
        familyPedigree(),
        narrativePedigree([
          disease('d1', 'Cancer', 'isEgo'),
          disease('d2', 'Cancer', 'hadTesting', 'node-color-seq-2'),
        ]),
      ]),
    );
    const stage = (result.protocol as { stages: Stage[] }).stages[1] as {
      diseases: { id: string; label: string }[];
    };
    expect(stage.diseases.map((row) => [row.id, row.label])).toEqual([
      ['d2', 'Cancer'],
    ]);
    expect(result.problems).toHaveLength(1);
    expect(result.problems[0]?.repair).toBe(
      'The conflicting disease will be removed.',
    );
  });

  // Only the highlight binding conflicts, so only it is removed. Dropping the
  // whole prompt would take its text, its layout variable and its edge
  // settings — and on a single-prompt Sociogram it cannot be dropped at all,
  // which used to refuse the protocol outright.
  it('removes only the offending highlight setting from a Sociogram prompt', async () => {
    const result = await expectRepairsToValidate(
      protocolWith([
        familyPedigree(),
        {
          id: 'sg1',
          label: 'Map your family',
          type: 'Sociogram',
          subject: { entity: 'node', type: 'family_member' },
          background: { concentricCircles: 4 },
          prompts: [
            {
              id: 'p1',
              text: 'Place your family',
              layout: { layoutVariable: 'fmLayout' },
              highlight: { allowHighlighting: true, variable: 'isEgo' },
            },
          ],
        },
      ]),
    );
    expect(result.problems).toEqual([
      {
        problem:
          '"is_ego" is set by the Family Pedigree interface, which marks the participant, but something else in this protocol also writes to it.',
        repair: 'The conflicting tap-to-highlight setting will be removed.',
      },
    ]);
    const stage = (result.protocol as { stages: Stage[] }).stages[1] as {
      prompts: Record<string, unknown>[];
    };
    expect(stage.prompts).toEqual([
      {
        id: 'p1',
        text: 'Place your family',
        layout: { layoutVariable: 'fmLayout' },
      },
    ]);
  });

  // The editors render interface-owned options read-only, so a protocol whose
  // options already drifted has no other way back.
  it('restores an interface-owned option set that was edited away', async () => {
    const protocol = protocolWith([familyPedigree()]);
    protocol.codebook.node.family_member.variables.biologicalSex = {
      name: 'biologicalSex',
      type: 'categorical',
      options: BIOLOGICAL_SEX_OPTIONS.map((option) =>
        option.value === 'female' ? { ...option, label: 'Woman' } : option,
      ),
    };
    const result = await expectRepairsToValidate(protocol);
    expect(result.problems[0]?.problem).toContain('biological sex options');
    expect(
      (
        result.protocol as {
          codebook: {
            node: Record<
              string,
              { variables: Record<string, { options: { label: string }[] }> }
            >;
          };
        }
      ).codebook.node.family_member!.variables.biologicalSex!.options,
    ).toEqual(BIOLOGICAL_SEX_OPTIONS);
  });

  // NetworkComposer's forms are optional and may be empty, unlike every other
  // `fields` array, so emptying one is a legitimate repair rather than a refusal.
  it('empties a NetworkComposer form rather than refusing the protocol', async () => {
    const result = await expectRepairsToValidate(
      protocolWith([
        familyPedigree(),
        {
          id: 'nc1',
          label: 'Compose',
          type: 'NetworkComposer',
          subject: { entity: 'node', type: 'family_member' },
          quickAdd: 'fmName',
          layoutVariable: 'fmLayout',
          background: { concentricCircles: 4, skewedTowardCenter: true },
          nodeForm: {
            fields: [
              { variable: 'age', component: 'Number' },
              { variable: 'age', component: 'Number' },
            ],
          },
        },
      ]),
    );
    const stage = (result.protocol as { stages: Stage[] }).stages[1] as {
      nodeForm: { fields: unknown[] };
    };
    expect(stage.nodeForm.fields).toEqual([
      { variable: 'age', component: 'Number' },
    ]);
  });

  it('refuses when the conflicting reference is a required stage slot', () => {
    // Two FamilyPedigree stages over one node type, where the second's LABEL
    // variable is the first's ego variable. Nothing can be dropped: both are
    // required fields.
    const result = repairConfigurationConflicts(
      protocolWith([
        familyPedigree(),
        familyPedigree({
          id: 'fp2',
          label: 'Second pedigree',
          nodeConfig: {
            type: 'family_member',
            nodeLabelVariable: 'isEgo',
            egoVariable: 'isEgo',
            relationshipVariable: 'relationshipToEgo',
            biologicalSexVariable: 'biologicalSex',
          },
        }),
      ]),
    );
    expect(result.repairable).toBe(false);
    expect(
      result.problems.some((problem) => problem.repair === undefined),
    ).toBe(true);
  });

  it('repairs several problems at once', async () => {
    const result = await expectRepairsToValidate(
      protocolWith([
        familyPedigree({
          nominationPrompts: [
            { id: 'np1', text: 'Who has this?', variable: 'hasConditionX' },
            { id: 'np2', text: 'Who is you?', variable: 'isEgo' },
          ],
          nodeConfig: {
            type: 'family_member',
            nodeLabelVariable: 'fmName',
            egoVariable: 'isEgo',
            relationshipVariable: 'relationshipToEgo',
            biologicalSexVariable: 'biologicalSex',
            form: [
              { variable: 'age', prompt: 'How old?' },
              { variable: 'age', prompt: 'How old again?' },
            ],
          },
        }),
        narrativePedigree([
          disease('d1', 'Condition X', 'hasConditionX'),
          disease('d2', 'Condition X', 'hadTesting', 'node-color-seq-2'),
        ]),
      ]),
    );
    expect(result.problems).toHaveLength(3);
  });

  it('never mutates the protocol it was given', () => {
    const protocol = protocolWith([
      familyPedigree({
        nominationPrompts: [
          { id: 'np1', text: 'Who is you?', variable: 'isEgo' },
          { id: 'np2', text: 'Who has this?', variable: 'hasConditionX' },
        ],
      }),
    ]);
    const before = JSON.stringify(protocol);
    repairConfigurationConflicts(protocol);
    expect(JSON.stringify(protocol)).toBe(before);
  });

  it('tolerates a non-object input', () => {
    expect(repairConfigurationConflicts(null)).toEqual({
      protocol: null,
      problems: [],
      repairable: true,
    });
  });
});
