import type { MessageDescriptor } from '@codaco/app-i18n/messages';
import type { Stage } from '@codaco/protocol-validation';

/**
 * The part of the editor a step points at. A section is found by the title the
 * editor gives it, so a step follows the section wherever the editor puts it;
 * a field is found by its form name, and falls back to its section while the
 * field is not on screen.
 */
export type StageWalkthroughTarget = Readonly<{
  section: MessageDescriptor;
  field?: string;
}>;

/**
 * A question the walkthrough asks. The option picked decides which later
 * steps are shown, through their `when`.
 */
export type StageWalkthroughChoice = Readonly<{
  id: string;
  options: readonly Readonly<{ id: string; label: MessageDescriptor }>[];
}>;

/** A screenshot of the interview, as generated by @codaco/interface-images. */
export type StageWalkthroughStill = Readonly<{
  variants: readonly Readonly<{ w: number; h: number; url: string }>[];
}>;

/**
 * One picture of what a setting does in the interview. A step with two shows
 * them one at a time behind a switch, labelled by `label` — usually the
 * interview without the setting, then with it.
 */
export type StageWalkthroughFrame = Readonly<{
  still: StageWalkthroughStill;
  alt: MessageDescriptor;
  label?: MessageDescriptor;
}>;

/** The choices that must have been made, and how, for a step to appear. */
export type StageWalkthroughCondition = Readonly<Record<string, string>>;

export type StageWalkthroughStep = Readonly<{
  id: string;
  title: MessageDescriptor;
  body: MessageDescriptor;
  /** Absent for the steps that introduce and close the walkthrough. */
  target?: StageWalkthroughTarget;
  optional?: boolean;
  choose?: StageWalkthroughChoice;
  visual?: readonly StageWalkthroughFrame[];
  when?: StageWalkthroughCondition;
  /**
   * Whether the stage on screen already has what this step asks for. Read
   * from the live draft, so the step reports done as soon as it is.
   */
  done?: (stage: Stage) => boolean;
}>;

export type StageWalkthrough = readonly StageWalkthroughStep[];
