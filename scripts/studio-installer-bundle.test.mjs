import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { parseEnv } from 'node:util';

import configurationFiles from '../apps/studio/deployment/installer/configuration-files.json' with { type: 'json' };
import { configureDeployment } from '../apps/studio/server/src/deployment/configure.ts';
import { readInstallerArchive } from './studio-installer-archive.mjs';
import { buildStudioInstaller } from './studio-installer-bundle.mjs';
import { readStudioCandidate } from './studio-release-policy.mjs';
import { releasedDistribution } from './test-support/studio-release.mjs';

const candidate = readStudioCandidate(process.cwd());
function fixture() {
  const value = releasedDistribution().value;
  value.source = candidate.commit;
  return {
    candidate,
    release: Buffer.from(JSON.stringify(value)),
    signature: Buffer.from(
      'retained opaque signature; authentication is a later gate',
    ),
  };
}
function substitute(input, path, bytes) {
  const oid = createHash('sha1')
    .update(`blob ${bytes.length}\0`)
    .update(bytes)
    .digest('hex');
  return {
    ...input,
    candidate: {
      ...input.candidate,
      files: input.candidate.files.map((file) =>
        file.path === path ? { ...file, oid } : file,
      ),
      read: (name) => (name === path ? bytes : input.candidate.read(name)),
    },
  };
}

test('packs committed installer code and exactly the public bytes generated by configure', async (t) => {
  const input = fixture();
  const packed = buildStudioInstaller(input);
  const archive = readInstallerArchive(packed.bytes, packed.manifestSha256);
  assert.deepEqual(buildStudioInstaller(input).bytes, packed.bytes);
  assert.deepEqual(archive.entries.get('release.json'), input.release);
  assert.deepEqual(
    archive.entries.get('release.sigstore.json'),
    input.signature,
  );
  for (const name of [
    'install.mjs',
    'operation.mjs',
    'smoke.mjs',
    'verify.mjs',
  ])
    assert.deepEqual(
      archive.entries.get(name),
      Buffer.from(candidate.read(`apps/studio/deployment/installer/${name}`)),
    );
  const generated = mkdtempSync(
    join(tmpdir(), 'studio-bundle-configure-control-'),
  );
  t.after(() => rmSync(generated, { recursive: true, force: true }));
  const images = JSON.parse(input.release).images;
  await configureDeployment(
    {
      domain: 'studio.example.test',
      email: 'operator@example.test',
      image: images.studio.reference,
      minioImage: images.minio.reference,
      output: generated,
    },
    join(process.cwd(), 'apps/studio'),
  );
  for (const name of configurationFiles) {
    assert.deepEqual(
      archive.entries.get(`templates/${name}`),
      Buffer.from(candidate.read(`apps/studio/${name}`)),
    );
    assert.deepEqual(
      archive.entries.get(`configuration/${name}`),
      readFileSync(join(generated, name)),
    );
  }
  const initialization = archive.entries
    .get('configuration/deployment/postgres-init.sql')
    .toString();
  assert.doesNotMatch(
    initialization,
    /STUDIO_RUNTIME_ROLES|STUDIO_LARGE_OBJECT_PRIVILEGES/,
  );
  assert.match(initialization, /CREATE ROLE "studio_app" NOLOGIN NOSUPERUSER/);
  assert.match(
    initialization,
    /REVOKE EXECUTE ON FUNCTION pg_catalog\.lo_create/,
  );
  const secrets = {
    ...parseEnv(readFileSync(join(generated, '.env'), 'utf8')),
    ...parseEnv(
      readFileSync(join(generated, 'deployment/encryption.env'), 'utf8'),
    ),
  };
  const roots = Object.entries(secrets)
    .filter(([name]) => /PASSWORD|SECRET|TOKEN|ROOT_.*_V1$/.test(name))
    .map(([, value]) => value)
    .filter(Boolean);
  assert.ok(roots.length >= 10);
  for (const secret of roots)
    assert.equal(packed.bytes.includes(Buffer.from(secret)), false);
  assert.ok(
    !packed.entries.some((name) =>
      /(?:^|\/)\.env$|encryption\.env$/.test(name),
    ),
  );
});

test('refuses content substituted beneath an unchanged committed blob identity', () => {
  const input = fixture();
  const path = 'apps/studio/deployment/installer/install.mjs';
  input.candidate = {
    ...candidate,
    read: (name) =>
      name === path ? 'export const substituted = true;' : candidate.read(name),
  };
  assert.throws(() => buildStudioInstaller(input), /committed Git blob/);
});

test('refuses missing entrypoints and links before producing an executable bundle', () => {
  for (const mode of ['missing', '120000']) {
    const input = fixture();
    input.candidate = {
      ...candidate,
      files: candidate.files.flatMap((file) =>
        file.path === 'apps/studio/deployment/installer/install.mjs'
          ? mode === 'missing'
            ? []
            : [{ ...file, mode }]
          : [file],
      ),
    };
    assert.throws(
      () => buildStudioInstaller(input),
      /incomplete|regular committed/,
    );
  }
});

test('refuses malformed provisioning, a different source, or an incompatible template inventory', () => {
  const input = fixture();
  const path = 'apps/studio/deployment/postgres-init.sql';
  const broken = Buffer.from(
    candidate.read(path).replace('/* STUDIO_RUNTIME_ROLES */', ''),
  );
  assert.throws(
    () => buildStudioInstaller(substitute(input, path, broken)),
    /Invalid database provisioning template/,
  );
  assert.throws(
    () =>
      buildStudioInstaller({
        ...input,
        candidate: { ...candidate, commit: 'f'.repeat(40) },
      }),
    /source differs/,
  );
  assert.throws(
    () =>
      buildStudioInstaller(
        substitute(
          input,
          'apps/studio/deployment/installer/configuration-files.json',
          Buffer.from('[]'),
        ),
      ),
    /inventory differs/,
  );
  for (const signature of [undefined, Buffer.alloc(0), '{}'])
    assert.throws(
      () => buildStudioInstaller({ ...input, signature }),
      /signature bundle/,
    );
});
